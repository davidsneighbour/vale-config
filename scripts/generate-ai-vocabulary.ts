import fs from "node:fs";

const patterns: string[] = JSON.parse(
  fs.readFileSync("scripts/data/ai-vocabulary.json", "utf8"),
);
const pattern = `(?i)(?:${patterns.join("|")})`;
const generated = new Map<string, string>();
generated.set(
  "styles/DNBAIPatterns/AIVocabulary.yml",
  `# Generated by scripts/generate-ai-vocabulary.ts; edit scripts/data/ai-vocabulary.json.\nextends: existence\nmessage: '"%s" is AI-associated vocabulary; consider whether a more precise word fits.'\nlevel: suggestion\nignorecase: true\nscope: ~blockquote\ntokens:\n${patterns.map((token) => `  - '${token.replaceAll("'", "''")}'`).join("\n")}\n`,
);
for (const level of ["warning", "error"] as const) {
  const condition =
    level === "error"
      ? "count >= 6 && rate >= 10.0"
      : "count >= 3 && rate >= 3.0 && !(count >= 6 && rate >= 10.0)";
  const content = `// Generated by scripts/generate-ai-vocabulary.ts; do not edit.\ntext := import("text")\ncandidates := text.re_find(${JSON.stringify(pattern)}, scope, -1)\nwords := text.re_find("[\\\\p{L}\\\\p{N}]+(?:['’-][\\\\p{L}\\\\p{N}]+)*", scope, -1)\nmatches := []\nif !is_undefined(candidates) && !is_undefined(words) && len(words) > 0 {\n    boundaries := {}\n    for word in words { boundaries[text.itoa(word[0].begin) + ":" + text.itoa(word[0].end)] = true }\n    hits := []\n    for candidate in candidates {\n        key := text.itoa(candidate[0].begin) + ":" + text.itoa(candidate[0].end)\n        if !is_undefined(boundaries[key]) { hits = append(hits, candidate) }\n    }\n    count := len(hits)\n    rate := float(count) * 1000.0 / float(len(words))\n    if ${condition} {\n        matches = [{begin: hits[0][0].begin, end: hits[0][0].end, message: "AI-associated vocabulary appears " + text.itoa(count) + " times in this paragraph (" + text.itoa(len(words)) + " words); review the wording. This does not establish AI authorship."}]\n    }\n}\n`;
  generated.set(
    `styles/config/scripts/vocabulary-density-${level}.tengo`,
    content,
  );
}
let stale = false;
for (const [file, content] of generated) {
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
      console.error(`Regenerate ${file} with npm run generate:ai`);
      stale = true;
    }
  } else {
    fs.writeFileSync(file, content);
  }
}
if (stale) process.exitCode = 1;
